#!/bin/sh
# SDL2 API for the Switch build: sdl2-compat linked statically to our SDL3.
#
# sdl2-compat normally dlopen()s SDL3.  Here SDL3 is a static archive whose
# SDL_* symbols are renamed SDL3x_SDL_* (they would clash with sdl2-compat's
# own SDL2 SDL_* exports), and "loading SDL3" is a lookup in a generated
# name -> address table (SDL2COMPAT_STATIC_SDL3).
# Usage: tools/build-sdl2compat-switch.sh <port-dir>   (e.g. ../doom-port)
#   clones sdl2-compat into <port-dir>/deps if needed; output goes to
#   <port-dir>/deps/sdl-switch/{libSDL2.a,libSDL3x.a,sdl3_static_table.o,include}
# Each port builds its own copy (ports stay independent).
set -e
TP=${HBX_DEPS_ROOT:?Set HBX_DEPS_ROOT to the directory holding build-sdl and sdl3}
AC=$(cd "${1:?usage: $0 <port-dir>}" && pwd)
PORT=$(cd "$(dirname "$0")" && pwd)
: "${HBXL_TOOLCHAIN:?Set HBXL_TOOLCHAIN}"
T=$HBXL_TOOLCHAIN/bin/aarch64-linux-musl
OUT=$AC/deps/sdl-switch
mkdir -p "$OUT"

# 1. Our SDL3 (hbx audio/joystick drivers), renamed.  TP's archive is read only.
cp "$TP/build-sdl/libSDL3.a" "$OUT/libSDL3x.a"
"$T-nm" --defined-only -g "$OUT/libSDL3x.a" 2>/dev/null |
    awk 'NF == 3 && $3 ~ /^SDL_/ { print $3 " SDL3x_" $3 }' | LC_ALL=C sort -u > "$OUT/sdl3-rename.map"
"$T-objcopy" --redefine-syms="$OUT/sdl3-rename.map" "$OUT/libSDL3x.a"

# 2. name -> address table for sdl2-compat's LookupSDL3Sym
{
    echo "/* generated by build-sdl2compat-switch.sh */"
    echo "#include <string.h>"
    awk '{ print "extern char " $2 "[];" }' "$OUT/sdl3-rename.map"
    echo "static const struct { const char* name; void* addr; } sdl3_static_syms[] = {"
    awk '{ print "    {\"" $1 "\", (void*)" $2 "}," }' "$OUT/sdl3-rename.map"
    echo "};"
    echo "void* SDL2COMPAT_StaticSDL3Lookup(const char* name) {"
    echo "    size_t lo = 0, hi = sizeof sdl3_static_syms / sizeof sdl3_static_syms[0];"
    echo "    while (lo < hi) { size_t mid = (lo + hi) / 2; int c = strcmp(sdl3_static_syms[mid].name, name);"
    echo "        if (c == 0) return sdl3_static_syms[mid].addr; if (c < 0) lo = mid + 1; else hi = mid; }"
    echo "    return 0;"
    echo "}"
} > "$OUT/sdl3_static_table.c"

# 3. sdl2-compat with the static loader branch
SRC=$AC/deps/sdl2-compat
if [ ! -d "$SRC" ]; then
    git clone -q https://github.com/libsdl-org/sdl2-compat.git "$SRC"
    git -C "$SRC" checkout -q "$(cat "$PORT/dependencies/sdl2-compat.commit")"
fi
if ! grep -q SDL2COMPAT_STATIC_SDL3 "$SRC/src/sdl2_compat.c"; then
    (cd "$SRC" && git apply "$PORT/patches/sdl2-compat-static-sdl3.diff")
fi
rm -rf "$AC/deps/build-sdl2compat-a64"
mkdir -p "$AC/deps/build-sdl2compat-a64"
cd "$AC/deps/build-sdl2compat-a64"
cmake "$SRC" -DCMAKE_TOOLCHAIN_FILE=$PORT/cmake/switch2-musl.cmake -DCMAKE_BUILD_TYPE=Release \
    -DSDL2COMPAT_STATIC=ON -DSDL2COMPAT_TESTS=OFF -DSDL2COMPAT_X11=OFF -DSDL2COMPAT_INSTALL=OFF \
    -DSDL3_INCLUDE_DIRS="$TP/sdl3/include" \
    -DCMAKE_C_FLAGS="-DSDL2COMPAT_STATIC_SDL3=1" > cfg.log 2>&1 || { tail -20 cfg.log; exit 1; }
make -j12 SDL2-static > build.log 2>&1 || { grep -m20 error build.log; exit 1; }
cp libSDL2.a "$OUT/libSDL2.a"
"$T-gcc" -O2 -mbranch-protection=bti -fno-pie -c "$OUT/sdl3_static_table.c" -o "$OUT/sdl3_static_table.o"
rm -rf "$OUT/include" && mkdir -p "$OUT/include" && cp -r "$SRC/include/SDL2" "$OUT/include/" && cp "$AC/deps/build-sdl2compat-a64/include/SDL2/"*.h "$OUT/include/SDL2/"
echo "sdl-switch: $(wc -l < "$OUT/sdl3-rename.map") SDL3 symbols renamed; $(ls "$OUT")"
